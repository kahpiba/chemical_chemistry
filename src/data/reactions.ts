export interface Reagent {
  id: string;
  name: string;
  nameId: string;
  formula: string;
  state: 'liquid' | 'solid' | 'powder';
  color: string;
  description: string;
  hazard?: 'corrosive' | 'flammable' | 'toxic' | 'irritant';
  pH?: number;
}

export type ReactionType = 
  | 'acid_base'
  | 'precipitation'
  | 'gas_evolution'
  | 'exothermic_redox'
  | 'catalytic_decomposition'
  | 'synthesis';

export interface ReactionEffect {
  liquidColorStart: string;
  liquidColorEnd: string;
  hasGas: boolean;
  gasSpeed: number; // 0 to 1
  gasColor: string;
  hasPrecipitate: boolean;
  precipitateColor: string;
  precipitateName: string;
  temperatureStart: number; // Celcius (default 25)
  temperatureEnd: number;
  steamEffect: boolean;
  glowOrSparks: boolean;
  pHStart?: number;
  pHEnd?: number;
  beakerCrack?: boolean;
  spatterEffect?: boolean;
  isHazardousFailure?: boolean;
  hazardType?: 'toxic_gas' | 'thermal_crack' | 'immiscible_phase' | 'alkali_explosion';
  isImmiscible?: boolean;
  immiscibleColors?: [string, string]; // [topColor, bottomColor]
}

export interface ReactionData {
  id: string;
  title: string;
  titleId: string;
  type: ReactionType;
  requiredReagents: string[]; // array of reagent IDs
  balancedEquation: string;
  deltaH: number; // kJ/mol (negative = exothermic, positive = endothermic)
  effects: ReactionEffect;
  summary: string;
  molecularExplanation: string;
  realWorldApplication: string;
  safetyWarning: string;
}

